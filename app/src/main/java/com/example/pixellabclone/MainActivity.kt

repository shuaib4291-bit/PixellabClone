package com.example.pixellabclone

import android.Manifest
import android.content.ContentValues
import android.content.pm.PackageManager
import android.graphics.Bitmap
import android.graphics.Color
import android.os.Build
import android.os.Bundle
import android.os.Environment
import android.provider.MediaStore
import android.widget.Button
import android.widget.EditText
import android.widget.Toast
import androidx.appcompat.app.AlertDialog
import androidx.appcompat.app.AppCompatActivity
import androidx.core.app.ActivityCompat
import androidx.core.content.ContextCompat
import java.io.OutputStream

class MainActivity : AppCompatActivity() {

    private lateinit var canvasView: CanvasView
    private var colorIndex = 0
    private val colors = listOf(Color.BLACK, Color.RED, Color.BLUE, Color.GREEN, Color.MAGENTA, Color.WHITE, Color.YELLOW)
    
    // পারমিশন রিকোয়েস্ট কোড
    private val STORAGE_PERMISSION_CODE = 101

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_main)

        canvasView = findViewById(R.id.canvasView)

        findViewById<Button>(R.id.btnAddText).setOnClickListener {
            showAddTextDialog()
        }

        findViewById<Button>(R.id.btnTextColor).setOnClickListener {
            colorIndex = (colorIndex + 1) % colors.size
            canvasView.changeTextColor(colors[colorIndex])
        }

        findViewById<Button>(R.id.btnTextSize).setOnClickListener {
            canvasView.increaseTextSize()
        }

        findViewById<Button>(R.id.btnBgColor).setOnClickListener {
            colorIndex = (colorIndex + 1) % colors.size
            canvasView.changeBgColor(colors[colorIndex])
        }

        findViewById<Button>(R.id.btnBold).setOnClickListener {
            canvasView.toggleBold()
        }

        findViewById<Button>(R.id.btnSave).setOnClickListener {
            checkPermissionAndSave()
        }
    }

    private fun showAddTextDialog() {
        val input = EditText(this)
        input.hint = "এখানে টেক্সট লিখুন..."
        AlertDialog.Builder(this)
            .setTitle("নতুন টেক্সট যোগ করুন")
            .setView(input)
            .setPositiveButton("যোগ করুন") { _, _ ->
                val text = input.text.toString()
                if (text.isNotEmpty()) {
                    canvasView.addText(text)
                }
            }
            .setNegativeButton("বাতিল", null)
            .show()
    }

    // পারমিশন চেক করার ফাংশন
    private fun checkPermissionAndSave() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            // Android 10+ এ কোনো পারমিশন লাগে না
            saveImageToGallery(canvasView.getBitmap())
        } else {
            // Android 9 এবং তার নিচের জন্য পারমিশন চেক
            if (ContextCompat.checkSelfPermission(this, Manifest.permission.WRITE_EXTERNAL_STORAGE)
                == PackageManager.PERMISSION_GRANTED) {
                saveImageToGallery(canvasView.getBitmap())
            } else {
                ActivityCompat.requestPermissions(
                    this,
                    arrayOf(Manifest.permission.WRITE_EXTERNAL_STORAGE),
                    STORAGE_PERMISSION_CODE
                )
            }
        }
    }

    // পারমিশন রেজাল্ট হ্যান্ডেল করা
    override fun onRequestPermissionsResult(
        requestCode: Int,
        permissions: Array<out String>,
        grantResults: IntArray
    ) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if (requestCode == STORAGE_PERMISSION_CODE) {
            if (grantResults.isNotEmpty() && grantResults[0] == PackageManager.PERMISSION_GRANTED) {
                saveImageToGallery(canvasView.getBitmap())
            } else {
                Toast.makeText(this, "ছবি সেভ করতে স্টোরেজ পারমিশন প্রয়োজন!", Toast.LENGTH_SHORT).show()
            }
        }
    }

    private fun saveImageToGallery(bitmap: Bitmap) {
        val filename = "Pixellab_${System.currentTimeMillis()}.png"
        var fos: OutputStream? = null

        try {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                val contentValues = ContentValues().apply {
                    put(MediaStore.MediaColumns.DISPLAY_NAME, filename)
                    put(MediaStore.MediaColumns.MIME_TYPE, "image/png")
                    put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_PICTURES + "/PixellabClone")
                }
                val imageUri = contentResolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, contentValues)
                fos = imageUri?.let { contentResolver.openOutputStream(it) }
            } else {
                val imagesDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_PICTURES)
                val image = java.io.File(imagesDir, filename)
                fos = java.io.FileOutputStream(image)
            }

            fos?.use {
                bitmap.compress(Bitmap.CompressFormat.PNG, 100, it)
                Toast.makeText(this, "ছবি গ্যালারিতে সেভ হয়েছে!", Toast.LENGTH_LONG).show()
            }
        } catch (e: Exception) {
            Toast.makeText(this, "সেভ করতে সমস্যা হয়েছে: ${e.message}", Toast.LENGTH_SHORT).show()
        }
    }
}